import assert from 'node:assert/strict'

export async function checkStudentPlanner(page, artifacts) {
  const nav = page.getByRole('navigation', { name: 'Основная навигация' })
  const planner = page.locator('#personal-schedule')
  const map = page.locator('#campus-activity')
  const tab = name => nav.getByRole('button', { name, exact: true }).click()
  const choice = id => planner.locator(`[data-club-choice="${id}"]`)
  const item = id => planner.locator(`[data-schedule-session="${id}"]`)
  const info = id => planner.locator(`[data-session-details="${id}"]`)
  const pickedIds = ['inter', 'mtg', 'board-games', 'book', 'mountain-tourism', 'academian-english', 'siberian-english', 'historical-political']
  const noOverflow = async label => assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, label)
  async function openOnMap(id) {
    await item(id).click()
    await info(id).waitFor()
    await info(id).getByRole('button', { name: 'Открыть место на карте' }).click()
    await map.locator(`[data-session-details="${id}"]`).waitFor()
  }
  await tab('Моё расписание')
  for (const id of pickedIds) await choice(id).check()
  await planner.getByLabel('Неделя расписания').fill('2026-11-09')
  await planner.getByRole('button', { name: 'Недельное расписание', exact: true }).click()
  assert.equal(await planner.locator('[data-schedule-day]').count(), 7)
  assert.equal(await item('board-games-sat').count(), 1)
  assert.equal(await planner.locator('[data-schedule-day] [data-schedule-session="bookclub-sun"]').count(), 0)
  assert.equal(await item('bookclub-sun').getAttribute('data-occurrence-date'), '')
  assert.equal(await planner.locator('[data-schedule-day] [data-schedule-session="historical-political-announced"]').count(), 0)
  assert.equal(await item('historical-political-announced').getAttribute('data-occurrence-date'), '')
  assert.equal(await item('mountain-run-mon').getByText('19:00', { exact: true }).count(), 1)
  assert.equal(await item('mountain-run-fri').getByText('19:00', { exact: true }).count(), 1)
  assert.equal(await item('academian-english-sun').getByText('17:30', { exact: true }).count(), 1)
  assert.equal(await planner.getByText('17:30–18:30', { exact: true }).count(), 0)
  // Two genuinely overlapping source intervals stack instead of covering each other.
  const mtg = await item('mtg-sat').boundingBox(), inter = await item('interclub-sat').boundingBox()
  assert.ok(mtg && inter && mtg.y + mtg.height <= inter.y)
  assert.notEqual(await item('mtg-sat').evaluate(el => getComputedStyle(el).borderLeftColor), await item('interclub-sat').evaluate(el => getComputedStyle(el).borderLeftColor))
  await item('interclub-sat').click()
  await info('interclub-sat').waitFor()
  await planner.getByRole('button', { name: 'Следующая неделя', exact: true }).click()
  assert.equal(await info('interclub-sat').count(), 0)
  assert.equal(await item('interclub-sat').getAttribute('data-occurrence-date'), '2026-11-21')
  await page.reload({ waitUntil: 'domcontentloaded' })
  await tab('Моё расписание')
  for (const id of pickedIds) assert.equal(await choice(id).isChecked(), true)
  await planner.getByLabel('Неделя расписания').fill('2026-11-09')
  await openOnMap('interclub-sat')
  const exactRoom = map.locator('polygon[data-room-id="academic-1-3314"]')
  await exactRoom.waitFor()
  assert.equal(await exactRoom.getAttribute('aria-pressed'), 'true')
  assert.equal(await exactRoom.getAttribute('fill'), '#16a34a')
  assert.equal(await map.getByLabel('Дата и время в Новосибирске').inputValue(), '2026-11-14T18:10')
  await tab('Моё расписание')
  await planner.getByRole('button', { name: 'Список занятий', exact: true }).click()
  await openOnMap('board-games-sat')
  await map.locator('[data-building-card="academic-1"]').waitFor()
  assert.equal(await map.locator('polygon[data-polygon-id]').count(), 0)
  const alternatives = map.locator('[data-session-details="board-games-sat"]')
  assert.equal(await alternatives.getByRole('button').count(), 3)
  await alternatives.getByRole('button', { name: 'Аудитория 2241', exact: true }).click()
  const candidate = map.locator('polygon[data-room-id="academic-1-2241"]')
  await candidate.waitFor()
  assert.equal(await candidate.getAttribute('aria-pressed'), 'true')
  assert.equal(await candidate.getAttribute('fill'), '#2563eb')
  await tab('Моё расписание')
  await openOnMap('bookclub-sun')
  await map.locator('polygon[data-room-id="academic-1-5272"]').waitFor()
  assert.equal(await map.getByLabel('Дата и время в Новосибирске').count(), 0)
  assert.equal(await map.locator('polygon[data-room-id="academic-1-5272"]').getAttribute('fill'), '#2563eb')
  await tab('Моё расписание')
  await openOnMap('mountain-run-mon')
  await map.locator('[data-building-card="sports-old"]').waitFor()
  assert.equal(await map.locator('polygon[data-polygon-id]').count(), 0)
  assert.ok(await map.locator('[data-session-details="mountain-run-mon"]').getByText('Старый спорткомплекс НГУ; конкретный зал не указан', { exact: false }).count())
  await tab('Каталог объединений')
  const catalogCard = page.getByLabel('Карточки объединений').locator('article').filter({ has: page.getByRole('heading', { name: 'Интерклуб НГУ', exact: true }) })
  await catalogCard.getByRole('button', { name: 'В расписание: Интерклуб НГУ', exact: true }).click()
  assert.equal(await choice('inter').isChecked(), true)
  assert.equal(await nav.getByRole('button', { name: 'Моё расписание', exact: true }).getAttribute('aria-current'), 'page')
  await choice('swing').check()
  assert.equal(await item('catalog-swing-wed').getAttribute('data-occurrence-date'), '2026-11-11')
  assert.equal(await item('catalog-swing-fri').getAttribute('data-occurrence-date'), '2026-11-13')
  await choice('digma').check()
  assert.equal(await item('catalog-digma-periodic').getAttribute('data-occurrence-date'), '')
  for (const width of [320, 390, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    await planner.getByRole('button', { name: width < 768 ? 'Список занятий' : 'Недельное расписание', exact: true }).click()
    await noOverflow(`${width}px personal schedule`)
    await planner.screenshot({ path: `${artifacts}/schedule-${width}.png` })
  }
  await planner.getByRole('button', { name: 'Сбросить выбор', exact: true }).click()
  assert.equal(await planner.locator('[data-schedule-session]').count(), 0)
  await page.reload({ waitUntil: 'domcontentloaded' })
  await tab('Моё расписание')
  for (const id of pickedIds) assert.equal(await choice(id).isChecked(), false)
  assert.deepEqual(JSON.parse(await page.evaluate(() => localStorage.getItem('nsu-activity:selected-clubs:v1'))), [])
  // Corrupt or blocked browser storage must not prevent choosing clubs.
  await page.evaluate(() => localStorage.setItem('nsu-activity:selected-clubs:v1', '{invalid'))
  await page.reload({ waitUntil: 'domcontentloaded' })
  await tab('Моё расписание')
  assert.equal(await choice('inter').isChecked(), false)
  await page.evaluate(() => localStorage.setItem('nsu-activity:selected-clubs:v1', '[]'))
  const isolated = await page.context().browser().newContext({ viewport: { width: 390, height: 844 } })
  try {
    await isolated.addInitScript(() => Object.defineProperty(window, 'localStorage', { get() { throw new DOMException('Blocked for test', 'SecurityError') } }))
    const blocked = await isolated.newPage()
    const errors = []
    blocked.on('pageerror', error => errors.push(error.message))
    await blocked.goto(page.url(), { waitUntil: 'domcontentloaded' })
    await blocked.getByRole('navigation', { name: 'Основная навигация' }).getByRole('button', { name: 'Моё расписание', exact: true }).click()
    await blocked.locator('[data-club-choice="inter"]').check()
    await blocked.getByRole('status').filter({ hasText: 'Браузер не разрешает сохранять выбор' }).waitFor()
    assert.equal(await blocked.locator('[data-schedule-session="interclub-sat"]').count(), 1)
    assert.deepEqual(errors, [])
  } finally { await isolated.close() }
  await tab('Карта кампуса')
  await map.locator('path[data-site-id="academic-1"]').waitFor()
  console.log(JSON.stringify({ personalSchedule: true, storageReload: true, reset: true, noGuessedDates: true, overlappingSessions: true, alternatives: true, calendarToFloor: true, buildingOnly: true, catalogueLink: true, mobile: [320, 390, 1440] }))
}
